"""Post-process scripts/audit_paraphrases.py output and emit Appendix E.

Reads paper/neurips_2026_v2/audit/paraphrase_audit.jsonl (one row per
audited pair), computes per-subtype mean / median / std / fraction <= 2,
collects up to 5 lowest-scoring examples per subtype, and emits a LaTeX
table fragment ready to paste into A-Appendix.tex (or `\input{}`).

Usage:
    python scripts/analyze_paraphrase_audit.py
"""
from __future__ import annotations

import json
import statistics
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
AUDIT = REPO / "paper" / "neurips_2026_v2" / "audit" / "paraphrase_audit.jsonl"
OUT_TEX = REPO / "paper" / "neurips_2026_v2" / "audit" / "appendix_E_table.tex"
OUT_LOWS = REPO / "paper" / "neurips_2026_v2" / "audit" / "appendix_E_lowscoring.tex"


def load_pairs():
    rows = [json.loads(line) for line in AUDIT.open() if line.strip()]
    return rows


def first_score(rec: dict) -> int | None:
    """Return the first available judge score in the record."""
    for k, v in rec.items():
        if k.endswith("_judgment") and isinstance(v, dict):
            s = v.get("score")
            if isinstance(s, int):
                return s
    return None


def first_reason(rec: dict) -> str:
    for k, v in rec.items():
        if k.endswith("_judgment") and isinstance(v, dict):
            return v.get("reason", "") or ""
    return ""


def main():
    if not AUDIT.exists():
        raise SystemExit(f"missing {AUDIT}; run scripts/audit_paraphrases.py first")
    rows = load_pairs()

    by_sub = defaultdict(list)
    for r in rows:
        s = first_score(r)
        if s is not None:
            by_sub[r["subtype"]].append((s, r))

    if not any(by_sub.values()):
        raise SystemExit(
            "audit JSONL has no '*_judgment' fields — looks like a dry-run output. "
            "Re-run scripts/audit_paraphrases.py without --dry-run."
        )

    OUT_TEX.parent.mkdir(parents=True, exist_ok=True)

    # Summary table
    lines = [
        "% Auto-generated by scripts/analyze_paraphrase_audit.py — do not edit by hand.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Paraphrase quality audit. For each LLM-generated subtype we audit "
        "$n$ random (clean, perturbed) pairs with a fixed-temperature judge and report "
        "mean / median / standard deviation of the 1--5 semantic-equivalence score, "
        "plus the fraction of pairs scored $\\leq 2$ (intent shifted or broken). "
        "Lower fractions are better.}",
        "\\label{tab:paraphrase-audit}",
        "\\small",
        "\\begin{tabular}{lrrrrr}",
        "\\toprule",
        "Subtype & $n$ & Mean & Median & Std & Fraction $\\leq 2$ \\\\",
        "\\midrule",
    ]
    for sub in ["Typo", "QueryPara", "ToolPara", "ParamPara"]:
        scored = [s for s, _ in by_sub.get(sub, [])]
        if not scored:
            lines.append(f"{sub} & 0 & --- & --- & --- & --- \\\\")
            continue
        n = len(scored)
        mean = statistics.fmean(scored)
        med = statistics.median(scored)
        sd = statistics.stdev(scored) if n > 1 else 0.0
        frac_bad = sum(1 for s in scored if s <= 2) / n
        # LaTeX needs the % sign escaped to avoid being read as a comment.
        lines.append(
            f"{sub} & {n} & {mean:.2f} & {med:.1f} & {sd:.2f} & "
            f"{frac_bad*100:.2f}\\% \\\\"
        )
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        "",
    ]
    OUT_TEX.write_text("\n".join(lines))
    print(f"wrote {OUT_TEX}")

    # Low-scoring examples (up to 5 per subtype). Each example is rendered as
    # a small block with three labeled lines (Clean / Perturbed / Judge) so the
    # reader can visually compare the two strings without scanning through one
    # long sentence. See user feedback on Appendix F formatting (round 12).
    def latex_safe(s: str) -> str:
        """Minimal escape for LaTeX: backslashes, underscores, braces, percent, ampersand, dollar."""
        if not s:
            return ""
        s = s.replace("\\", r"\textbackslash{}")
        s = s.replace("&", r"\&").replace("%", r"\%").replace("$", r"\$")
        s = s.replace("#", r"\#").replace("_", r"\_")
        s = s.replace("{", r"\{").replace("}", r"\}")
        s = s.replace("~", r"\textasciitilde{}").replace("^", r"\textasciicircum{}")
        return s.replace("\n", " ")

    lows = ["% Auto-generated low-scoring examples for Appendix F.", ""]
    for sub in ["Typo", "QueryPara", "ToolPara", "ParamPara"]:
        items = sorted(by_sub.get(sub, []), key=lambda kv: kv[0])[:5]
        if not items:
            continue
        lows.append(f"\\paragraph{{{sub} --- lowest-scoring 5 audited pairs.}}")
        lows.append("")
        for sc, rec in items:
            sid = latex_safe(rec.get("sample_id", "?"))
            cl = latex_safe((rec.get("clean_excerpt") or "")[:240])
            pe = latex_safe((rec.get("perturbed_excerpt") or "")[:240])
            reason = latex_safe(first_reason(rec)[:240])
            lows.append(f"\\noindent\\textbf{{Score {sc}}} \\quad \\emph{{(sample id: \\texttt{{{sid}}})}}")
            lows.append("")
            lows.append("\\begin{adjustwidth}{1em}{0pt}")
            lows.append(f"\\textit{{Clean:}}~``{cl}\\ldots''\\\\[2pt]")
            lows.append(f"\\textit{{Perturbed:}}~``{pe}\\ldots''\\\\[2pt]")
            lows.append(f"\\textit{{Judge:}}~{reason}")
            lows.append("\\end{adjustwidth}")
            lows.append("")
        lows.append("")
    OUT_LOWS.write_text("\n".join(lows))
    print(f"wrote {OUT_LOWS}")

    # Console headline
    print()
    print("=" * 60)
    print("Audit headline:")
    for sub in ["Typo", "QueryPara", "ToolPara", "ParamPara"]:
        scored = [s for s, _ in by_sub.get(sub, [])]
        if scored:
            mean = statistics.fmean(scored)
            frac = sum(1 for s in scored if s <= 2) / len(scored)
            print(f"  {sub:10s}  n={len(scored):3d}  mean={mean:.2f}  "
                  f"fraction<=2={frac:.2%}")


if __name__ == "__main__":
    main()
